export function getSpot(id: string): Spot | undefined {
  return SPOTS.find((s) => s.id === id);
}

export function spotsByCategory(category: SpotCategory): Spot[] {
  return SPOTS.filter((s) => s.category === category);
}

/**
 * Photo-density score 0–1: higher = many motifs per step, ideal for "wenig laufen, viel sehen" spots.
 */
export function photoDensityScore(s: Spot): number {
  if (!s.motifsPerStep) return 0;
  const stepsPenalty = s.effort ? Math.min(1, 200 / Math.max(s.effort.steps, 50)) : 0.5;
  return s.motifsPerStep * stepsPenalty;
}

/**
 * Readable Foto-Schritt-Ranking label.
 */
export function photoDensityLabel(s: Spot): string {
  const score = photoDensityScore(s);
  if (score >= 0.7) return "Hoch — viele Motive, kurze Wege";
  if (score >= 0.4) return "Mittel — solide Ausbeute";
  if (score > 0)    return "Verteilt — weite Wege, wenige Spots";
  return "—";
}

/**
 * Effort label from step count.
 */
export function effortLabel(s: Spot): string {
  if (!s.effort) return "—";
  if (s.effort.steps < 200)  return "Entspannt";
  if (s.effort.steps < 800)  return "Moderat";
  if (s.effort.steps < 2000) return "Aktiv";
  return "Anstrengend";
}
